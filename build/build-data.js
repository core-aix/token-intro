#!/usr/bin/env node
// Builds assets/data.js from the prompt definitions and the real Claude Haiku 4.5
// responses captured in build/responses/. Everything the page needs is baked in
// here so the demo runs standalone with no backend.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const tok = require(path.join(__dirname, 'vendor', 'cl100k_base.js'));

// Claude Haiku 4.5 published rates, US dollars per million tokens.
const RATE_IN = 1.0;
const RATE_OUT = 5.0;

const prompts = JSON.parse(fs.readFileSync(path.join(__dirname, 'prompts.json'), 'utf8'));

/** Split text into the individual token strings, so the page can show them. */
function tokenise(text) {
  return tok.encode(text).map((id) => tok.decode([id]));
}

const examples = prompts.map((p) => {
  const raw = JSON.parse(
    fs.readFileSync(path.join(__dirname, 'responses', `${p.id}.json`), 'utf8')
  );
  const answer = raw.result;

  const inTokens = tokenise(p.prompt);
  const outTokens = tokenise(answer);

  const costIn = (inTokens.length / 1e6) * RATE_IN;
  const costOut = (outTokens.length / 1e6) * RATE_OUT;

  return {
    id: p.id,
    label: p.label,
    blurb: p.blurb,
    prompt: p.prompt,
    answer,
    inTokens,
    outTokens,
    inCount: inTokens.length,
    outCount: outTokens.length,
    costIn,
    costOut,
    costTotal: costIn + costOut,
    // Output tokens the API actually billed, which include the model's hidden
    // "thinking" as well as the visible answer. Kept for the honesty note.
    billedOutTokens: raw.usage && raw.usage.output_tokens,
  };
});

const data = {
  model: 'Claude Haiku 4.5',
  rateIn: RATE_IN,
  rateOut: RATE_OUT,
  generated: new Date().toISOString().slice(0, 10),
  examples,
};

fs.mkdirSync(path.join(ROOT, 'assets'), { recursive: true });
fs.writeFileSync(
  path.join(ROOT, 'assets', 'data.js'),
  '/* Generated by build/build-data.js — do not edit by hand. */\n' +
    'window.TOKEN_DEMO_DATA = ' +
    JSON.stringify(data) +
    ';\n'
);

console.log(`Wrote assets/data.js — ${examples.length} examples`);
for (const e of examples) {
  console.log(
    `  ${e.id.padEnd(16)} in ${String(e.inCount).padStart(4)}  out ${String(
      e.outCount
    ).padStart(4)}  $${e.costTotal.toFixed(6)}`
  );
}
